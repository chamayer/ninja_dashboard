def test_projection_is_state_idempotent_not_write_free(pg) -> None:
    """State-idempotent, deliberately not write-free.

    The upsert's DO UPDATE always fires, refreshing `last_observed_at`, so a
    second run reports 1 written rather than 0. That refresh is the record that
    the evidence is still supported, which is what makes a later withdrawal
    meaningful -- so the write is wanted. What must not change is the row count
    or `first_observed_at`: a re-observation is not a new observation.
    """
    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        _product(cur, "acme control", "Acme Ltd")
        _rule(cur, "acme", "remote_access", title="acme control")

    _project(pg["admin"])
    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("SELECT first_observed_at FROM catalog.capability_assertion_machine")
        first = cur.fetchone()[0]

    written, withdrawn, _, _ = _project(pg["admin"])

    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT count(*), min(first_observed_at), max(last_observed_at) FROM "
            "catalog.capability_assertion_machine WHERE withdrawn_at IS NULL"
        )
        count, still, last_seen = cur.fetchone()
    assert count == 1, "no duplicate row"
    assert still == first, "a re-observation is not a new observation"
    assert withdrawn == 0
    assert written == 1, (
        "the upsert refreshes last_observed_at, so a second run updates rather "
        "than writing nothing -- state-idempotent, not write-free"
    )
    assert last_seen >= first


