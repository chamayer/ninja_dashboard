def test_ingest_role_boundaries(pg) -> None:
    """The grants as written, exercised against a NON-superuser ingest role.

    Production ingest currently connects as a superuser and bypasses all of
    this; the point of the test is that the grants are correct now, so the
    boundary begins holding the moment that changes.
    """
    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        uuid_ = _product(cur, "acme control")
        cur.execute(
            "INSERT INTO catalog.capability_assertion_operator "
            "(product_uuid, capability, polarity, confirmed_by) "
            "VALUES (%s,'rmm',TRUE,'curator')", (uuid_,),
        )

    with psycopg.connect(pg["role_dsn"]("ninja_ingest"), autocommit=True) as conn:
        with conn.cursor() as cur:
            cur.execute(
                "INSERT INTO catalog.capability_assertion_machine "
                "(product_uuid, capability, source_key, confidence, evidence_kind, "
                " matcher_version) VALUES (%s,'rmm','vetted_rule',0.9,'x','t')",
                (uuid_,),
            )
        forbidden = [
            "UPDATE catalog.capability_assertion_operator SET polarity = FALSE",
            "INSERT INTO catalog.capability_assertion_operator "
            "(product_uuid, capability, polarity, confirmed_by) "
            "SELECT product_uuid,'rmm',FALSE,'x' FROM catalog.products",
            "UPDATE catalog.capability_source SET may_alert = FALSE "
            "WHERE source_key = 'lolrmm'",
            "INSERT INTO catalog.capability_rule "
            "(rule_key, capability, title_pattern, source_key) "
            "VALUES ('x','rmm','y','vetted_rule')",
            "DELETE FROM catalog.capability_assertion_machine",
            # Immutable machine columns.
            "UPDATE catalog.capability_assertion_machine SET capability = 'rmm'",
            "UPDATE catalog.capability_assertion_machine SET source_key = 'lolrmm'",
        ]
