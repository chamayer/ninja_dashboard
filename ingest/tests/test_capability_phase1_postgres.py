def test_colliding_rules_collapse_deterministically(pg) -> None:
    """Two rules matching one product previously raised
    'ON CONFLICT DO UPDATE command cannot affect row a second time'."""
    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        uuid_ = _product(cur, "acme remote desktop", "Acme Ltd")
        # Same specificity, different priority -> lower priority number wins.
        _rule(cur, "b_low_priority", "remote_access", title="acme remote%", priority=50)
        _rule(cur, "a_high_priority", "remote_access", title="acme remote desktop", priority=10)

    _project(pg["admin"])

    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT evidence_ref, count(*) OVER () FROM "
            "catalog.capability_assertion_machine WHERE product_uuid = %s "
            "AND withdrawn_at IS NULL", (uuid_,),
        )
        rows = cur.fetchall()
    assert len(rows) == 1, "collision must collapse to one current row"
    assert rows[0][0] == "a_high_priority", "lowest priority number wins"


