def test_empty_rule_set_preserves_prior_assertions(pg) -> None:
    """A rule table that failed to load looks exactly like one matching
    nothing. Treating them alike would withdraw the whole corpus.

    This drives the projector's real control flow -- asserting the guard's
    *condition* would not prove it takes the branch.
    """
    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        uuid_ = _product(cur, "acme control", "Acme Ltd")
        _rule(cur, "acme", "remote_access", title="acme control")
    _project(pg["admin"])

    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("DELETE FROM catalog.capability_rule")

    # The real guard, executed.
    with psycopg.connect(pg["admin"]) as conn, conn.cursor() as cur:
        written, withdrawn, rules, evaluated = capability_match.project_with_cursor(cur)
        conn.commit()

    assert (written, withdrawn, rules, evaluated) == (0, 0, 0, []), (
        "an empty rule set must return without touching anything"
    )

    with psycopg.connect(pg["admin"], autocommit=True) as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT count(*) FROM catalog.capability_assertion_machine "
            "WHERE withdrawn_at IS NULL AND product_uuid = %s", (uuid_,)
        )
        assert cur.fetchone()[0] == 1, "prior evidence must survive"
        assert _effective(cur, uuid_) == [("remote_access", "asserted", True)]


