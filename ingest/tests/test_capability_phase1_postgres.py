# ── helpers ─────────────────────────────────────────────────────────────────

def _product(cur, name: str, publisher: str | None = None) -> str:
    pub_id = None
    if publisher is not None:
        cur.execute(
            "INSERT INTO catalog.publishers (canonical_name) VALUES (%s) RETURNING id",
            (publisher,),
        )
        pub_id = cur.fetchone()[0]
    cur.execute(
        "INSERT INTO catalog.products (publisher_id, canonical_name) "
        "VALUES (%s, %s) RETURNING product_uuid",
        (pub_id, name),
    )
    return cur.fetchone()[0]


def _rule(cur, key: str, capability: str, *, title="", publisher="",
          source="vetted_rule", priority=100, enabled=True) -> None:
    cur.execute(
        "INSERT INTO catalog.capability_rule "
        "(rule_key, capability, title_pattern, publisher_pattern, source_key, "
        " priority, enabled) VALUES (%s,%s,%s,%s,%s,%s,%s)",
        (key, capability, title, publisher, source, priority, enabled),
    )


def _project(dsn: str) -> tuple[int, int, int, list[str]]:
    """Run the real projector against the disposable container.

    One execution path: these tests drive `project_with_cursor` itself rather
    than a copy of its SQL, so a change to the projector cannot pass here while
    breaking in production.

    Not autocommit: `_COMPUTE_SQL` builds a TEMP TABLE ... ON COMMIT DROP, so
    every statement committing on its own would drop it before the write.
    """
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        result = capability_match.project_with_cursor(cur)
        conn.commit()
    return result


def _effective(cur, product_uuid: str) -> list[tuple]:
    cur.execute(
        "SELECT capability, state, alertable FROM "
        "catalog.v_product_capability_effective WHERE product_uuid = %s "
        "ORDER BY capability",
        (product_uuid,),
    )
    return cur.fetchall()


