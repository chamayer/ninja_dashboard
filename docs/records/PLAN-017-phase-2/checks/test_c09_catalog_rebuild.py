"""Check 9 — catalog reconstruction after a cleared link and a clean rebuild (F07).

Runs the real projector statements from ingest/software_catalog.py, in the
order `project_software_catalog` runs them, against the catalog schema of SQL
074/075/076.
"""

from __future__ import annotations

import uuid

import psycopg
import pytest

from ingest import software_catalog as catalog

CATALOG_SCHEMA = """
CREATE SCHEMA catalog;
CREATE TABLE catalog.publishers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name text NOT NULL,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_catalog_publishers_name UNIQUE (canonical_name)
);
CREATE TABLE catalog.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_id bigint REFERENCES catalog.publishers(id) ON DELETE RESTRICT,
    canonical_name text NOT NULL,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    product_uuid uuid NOT NULL DEFAULT gen_random_uuid(),
    CONSTRAINT uq_catalog_products_publisher_name
        UNIQUE NULLS NOT DISTINCT (publisher_id, canonical_name),
    CONSTRAINT uq_catalog_products_uuid UNIQUE (product_uuid)
);
CREATE TABLE catalog.software_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES catalog.products(id) ON DELETE RESTRICT,
    version text NOT NULL DEFAULT '',
    eol_date date,
    eol_source text NOT NULL DEFAULT '',
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version_uuid uuid NOT NULL DEFAULT gen_random_uuid(),
    CONSTRAINT uq_catalog_versions_product_version UNIQUE (product_id, version),
    CONSTRAINT uq_catalog_versions_uuid UNIQUE (version_uuid)
);
CREATE SCHEMA operations;
CREATE TABLE operations.publisher_aliases (
    raw_pattern text NOT NULL, canonical_publisher text NOT NULL, enabled boolean NOT NULL
);
CREATE TABLE operations.software_installations_current (
    tenant_id bigint NOT NULL, client_id uuid NOT NULL, device_id uuid NOT NULL,
    canonical_name text NOT NULL, publisher text, version text,
    deleted_at timestamptz,
    software_version_id bigint REFERENCES catalog.software_versions(id) ON DELETE RESTRICT,
    PRIMARY KEY (tenant_id, client_id, device_id, canonical_name)
);
-- Stand-in for authored state keyed by the durable product UUID
-- (capability/category assertions, authorizations, finding subjects).
CREATE TABLE operations.authored_product_reference (
    product_uuid uuid NOT NULL, note text NOT NULL
);
INSERT INTO operations.publisher_aliases VALUES ('Acme%', 'Acme', true);
"""

CLIENT, DEVICE = uuid.uuid4(), uuid.uuid4()


@pytest.fixture
def conn(postgres_dsn):
    with psycopg.connect(postgres_dsn, autocommit=True) as setup:
        setup.execute("DROP SCHEMA IF EXISTS operations CASCADE")
        setup.execute("DROP SCHEMA IF EXISTS catalog CASCADE")
        setup.execute(CATALOG_SCHEMA)
    with psycopg.connect(postgres_dsn) as connection:
        yield connection


def _install(conn, name, version, publisher="Acme Corp"):
    with conn.transaction():
        conn.execute(
            "INSERT INTO operations.software_installations_current"
            " (tenant_id, client_id, device_id, canonical_name, publisher, version)"
            " VALUES (1, %s, %s, %s, %s, %s)",
            (CLIENT, DEVICE, name, publisher, version),
        )


def _project(conn) -> dict[str, int]:
    counts = {}
    with conn.transaction():
        for key, sql in (
            ("publishers", catalog._UPSERT_PUBLISHERS),
            ("products", catalog._UPSERT_PRODUCTS),
            ("versions", catalog._UPSERT_VERSIONS),
        ):
            counts[key] = conn.execute(sql).rowcount
    linked = 0
    while True:
        with conn.transaction():
            written = conn.execute(catalog._BACKFILL_LINKS).rowcount
        linked += written
        if written == 0:
            break
    counts["linked"] = linked
    return counts


def _products(conn):
    return dict(
        conn.execute("SELECT canonical_name, product_uuid FROM catalog.products").fetchall()
    )


def _links(conn):
    return conn.execute(
        "SELECT i.canonical_name, v.version, p.product_uuid"
        "  FROM operations.software_installations_current i"
        "  LEFT JOIN catalog.software_versions v ON v.id = i.software_version_id"
        "  LEFT JOIN catalog.products p ON p.id = v.product_id ORDER BY 1"
    ).fetchall()


def test_in_place_rerun_is_idempotent_and_keeps_identities(conn):
    _install(conn, "Widget", "1.0")
    assert _project(conn) == {"publishers": 1, "products": 1, "versions": 1, "linked": 1}
    before = (_products(conn), _links(conn))
    assert _project(conn) == {"publishers": 0, "products": 0, "versions": 0, "linked": 0}
    assert (_products(conn), _links(conn)) == before


def test_cleared_link_relinks_and_keeps_the_old_version(conn):
    _install(conn, "Widget", "1.0")
    _project(conn)
    product_uuid = _products(conn)["Widget"]
    # A version change clears the link for relinking (software inventory apply).
    with conn.transaction():
        conn.execute(
            "UPDATE operations.software_installations_current"
            " SET version = '2.0', software_version_id = NULL"
        )
    assert _project(conn)["linked"] == 1
    assert _links(conn) == [("Widget", "2.0", product_uuid)]
    versions = conn.execute(
        "SELECT version FROM catalog.software_versions ORDER BY 1"
    ).fetchall()
    assert versions == [("1.0",), ("2.0",)]


def test_referenced_version_cannot_be_deleted(conn):
    _install(conn, "Widget", "1.0")
    _project(conn)
    with pytest.raises(psycopg.errors.ForeignKeyViolation), conn.transaction():
        conn.execute("DELETE FROM catalog.software_versions")


def test_reproduces_clean_rebuild_is_not_identical(conn):
    """F07: dropping and rebuilding does not recreate the same catalog."""
    _install(conn, "Widget", "1.0")
    _install(conn, "Old Tool", "3.1")
    _project(conn)
    old = _products(conn)
    with conn.transaction():
        conn.execute(
            "INSERT INTO operations.authored_product_reference VALUES (%s, 'approved'),"
            " (%s, 'reviewed')",
            (old["Widget"], old["Old Tool"]),
        )
        # Old Tool's last installation disappears; its product is retained.
        conn.execute(
            "DELETE FROM operations.software_installations_current"
            " WHERE canonical_name = 'Old Tool'"
        )

    # Clean rebuild in the disposable database: unlink, drop catalog rows, rerun.
    with conn.transaction():
        conn.execute(
            "UPDATE operations.software_installations_current SET software_version_id = NULL"
        )
        conn.execute("DELETE FROM catalog.software_versions")
        conn.execute("DELETE FROM catalog.products")
        conn.execute("DELETE FROM catalog.publishers")
    _project(conn)
    new = _products(conn)

    assert set(new) == {"Widget"}                    # retained product not recreated
    assert new["Widget"] != old["Widget"]            # same product, new durable UUID
    dangling = conn.execute(
        "SELECT r.note FROM operations.authored_product_reference r"
        " LEFT JOIN catalog.products p ON p.product_uuid = r.product_uuid"
        " WHERE p.id IS NULL ORDER BY 1"
    ).fetchall()
    assert dangling == [("approved",), ("reviewed",)]
