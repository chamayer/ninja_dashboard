def _record(conn, instance, entity_type, data, active=True):
    observation_id = uuid.uuid4()
    conn.execute(
        """INSERT INTO operations.entity_observation_current VALUES
               (%s, 1, %s, %s, 'x', %s, '', %s, %s, now(), %s::jsonb)""",
        (observation_id, uuid.uuid4(), instance, entity_type, str(observation_id), active,
         json.dumps(data)),
    )
    return conn.execute(
        """SELECT record_lifecycle, counts_as_current_computer_evidence
             FROM operations.v_device_source_record_lifecycle_current
            WHERE observation_id = %s""",
        (observation_id,),
    ).fetchone()


def test_documentation_and_stopped_vms_are_not_evidence(conn):
    assert _record(conn, HUDU, "cmdb.asset", {"archived": False}) == ("documentation", False)
    assert _record(conn, HUDU, "cmdb.asset", {"archived": True}) == ("archived", False)
    assert _record(conn, NINJA, "vm.guest", {"power_state": "poweredoff"}) == ("stopped", False)
    assert _record(conn, NINJA, "vm.guest", {"power_state": "suspended"}) == ("stopped", False)
    assert _record(conn, NINJA, "vm.guest", {"power_state": "poweredon"}) == ("unknown", True)
    assert _record(conn, NINJA, "agent.rmm", {"is_online": False}) == ("unknown", True)


def test_the_finding_type_and_policy_register_once(conn):
    row = conn.execute(
        """SELECT finding_class, alertable, covered_by, cover_note, issue_group
             FROM operations.finding_types WHERE name = 'archived_but_reporting'"""
    ).fetchone()
    assert row == ("entity", False, [], "", "Computer lifecycle")
    active = conn.execute(
        "SELECT version, policy FROM operations.condition_policy_versions WHERE active"
    ).fetchone()
    assert active[0] == "conditions-registry-4"
    assert "archived_but_reporting" in [d["name"] for d in active[1]["definitions"]]
    migration = importlib.import_module("apps.core.migrations.0310_listing_evidence_and_retirement")
    migration.register_finding_type(None, _SchemaEditor(conn))
    assert conn.execute(
        "SELECT count(*) FROM operations.condition_policy_versions"
    ).fetchone()[0] == 2


def test_an_archived_only_source_does_not_satisfy_a_requirement(conn):
    """ingest.evaluator._PRESENCE_SATISFIES against the production view."""
    from ingest.evaluator import _PRESENCE_SATISFIES

    conn.execute(
        """CREATE TABLE IF NOT EXISTS operations.device_agent_presence_current (
               tenant_id bigint NOT NULL, device_id uuid NOT NULL,
               entity_type varchar(80) NOT NULL, platform varchar(80) NOT NULL)"""
    )

    def satisfied(*assets):
        device = uuid.uuid4()
        for archived in assets:
            conn.execute(
                """INSERT INTO operations.entity_observation_current VALUES
                       (%s, 1, %s, %s, 'Hudu', 'cmdb.asset', '', %s, true, now(), %s::jsonb)""",
                (uuid.uuid4(), device, HUDU, str(uuid.uuid4()), json.dumps({"archived": archived})),
            )
        conn.execute(
            "INSERT INTO operations.device_agent_presence_current VALUES (1, %s, 'cmdb.asset', 'Hudu')",
            (device,),
        )
        return conn.execute(
            f"""SELECT count(*) FROM operations.device_agent_presence_current apc
                 WHERE apc.device_id = %s {_PRESENCE_SATISFIES}""",
            (device,),
        ).fetchone()[0] == 1

    assert satisfied(False)
    assert satisfied(True, False)  # an archived asset beside a current one: replaced
    assert not satisfied(True)
    assert not satisfied(True, True)


